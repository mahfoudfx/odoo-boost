"""odoo-boost uninstall – clean up generated agent files and optionally remove config."""

from __future__ import annotations

from pathlib import Path
from typing import Annotated

import typer
from rich.console import Console

from odoo_boost.agents import iter_agents
from odoo_boost.cli.files import report_paths
from odoo_boost.cli.gitignore import ignore_entry, managed_entries, update_gitignore
from odoo_boost.config.settings import find_config_path, load_config

console = Console()


def uninstall(
    config: Annotated[
        Path | None, typer.Option("--config", "-c", help="Path to odoo-boost.json")
    ] = None,
    keep_config: Annotated[
        bool,
        typer.Option(
            "--keep-config",
            help="Keep odoo-boost.json and remove only generated agent files.",
        ),
    ] = False,
    yes: Annotated[
        bool,
        typer.Option(
            "--yes",
            "-y",
            help="Skip confirmation prompts and delete files.",
        ),
    ] = False,
    gitignore: Annotated[
        bool | None,
        typer.Option(
            "--gitignore/--no-gitignore", help="Remove managed entries for deleted files."
        ),
    ] = None,
) -> None:
    """Remove files generated by Odoo Boost for configured agents."""
    config = config or find_config_path()
    try:
        cfg = load_config(config)
    except FileNotFoundError:
        console.print("[red]No odoo-boost.json found.[/]")
        raise typer.Exit(1) from None

    project_path = cfg.project_root

    if not yes:
        # Prompt if the user wants to keep agent files. Default is False (delete them).
        keep_files = typer.confirm(
            "Do you want to keep generated agent files (AGENTS.md, configs, skills)?",
            default=False,
        )
        if keep_files:
            console.print("[yellow]Aborted uninstall. Keeping all files.[/]")
            raise typer.Exit(0)

        if not keep_config:
            # Prompt if the user wants to keep the config file. Default is False (delete it).
            keep_cfg_prompt = typer.confirm(
                "Do you want to keep your configuration file (odoo-boost.json)?",
                default=False,
            )
            if keep_cfg_prompt:
                keep_config = True

    console.print("[bold]Uninstalling Odoo Boost files…[/]\n")

    removed_files: list[Path] = []
    for agent in iter_agents(cfg, project_path):
        removed_paths = agent.uninstall()
        removed_files.extend(removed_paths)
        report_paths(console, removed_paths, project_path, "[red]Removed[/]")

    if not keep_config:
        cfg_file = config or (project_path / "odoo-boost.json")
        if cfg_file.is_file():
            cfg_file.unlink()
            removed_files.append(cfg_file)
            report_paths(console, [cfg_file], project_path, "[red]Removed[/]")

    managed = managed_entries(project_path)
    removable = {
        ignore_entry(project_path, path)
        for path in removed_files
        if path.absolute().is_relative_to(project_path.absolute()) and not path.exists()
    } & managed
    if removable:
        console.print("\n[bold]Managed .gitignore entries for removed files:[/]")
        for entry in sorted(removable):
            console.print(f"  {entry}", markup=False)
        if gitignore is True or (
            gitignore is None
            and not yes
            and typer.confirm("Remove these entries from .gitignore?", default=False)
        ):
            update_gitignore(project_path, remove=removable)
            console.print("  [green]Updated[/] .gitignore")

    if not removed_files:
        console.print("  [dim]No generated files found to remove.[/]")

    console.print("\n[green]Uninstall complete![/]")
